WORLDS = ("identity", "global", "conditional", "nonlinear")


def source_records(seed):
    """Read only the original source observations and validate full prefix support."""
    path = BASE / f"F05/source_full_r2/core_{seed}/source.jsonl"
    groups = {}
    for line in path.read_text().splitlines():
        row = json.loads(line)
        if row["role"] != "source" or row["world"] != "core":
            raise ValueError("wrong source role/world")
        groups.setdefault(row["author_id"], []).append(row)
    ids = sorted(groups)
    z = np.array([r["z"] for r in groups[ids[0]][:48]])
    for rows in groups.values():
        if len(rows) < 48 or [r["t"] for r in rows[:48]] != list(range(48)):
            raise ValueError("source time support mismatch")
        np.testing.assert_array_equal([r["z"] for r in rows[:48]], z)
    return path, ids, np.array([[r["y"] for r in groups[i][:48]] for i in ids]), z


def prepare(output, seed, smoke):
    """Freeze observed pilot calibrations before any application inference."""
    folder = output / str(seed)
    ready = folder / "prepared.json"
    if ready.exists():
        for name, h in json.loads(ready.read_text())["hashes"].items():
            if public.file_hash(folder / name) != h:
                raise ValueError("prepared input changed")
        return
    folder.mkdir(exist_ok=True)
    old_path = BASE / f"F16/t2_cold_full_r1/{seed}/bundle.json"
    old = json.loads(old_path.read_text())
    validate_bundle(old)
    if len(old["source_models"]) != 200:
        raise ValueError("incomplete frozen source models")
    save(folder / "source_bundle.json", old)
    for role, count in [("pilot", 100), ("application", 200)]:
        observed, truth = law.simulate(seed, role, count)
        np.savez(folder / f"{role}_observations.npz", **observed)
        np.savez(folder / f"{role}_truth.npz", **truth)
    # Truth is generated by the simulator only, never passed to calibration/scoring.
    pilot = np.load(folder / "pilot_observations.npz")
    y, z = pilot["old"], pilot["conditions"]
    indices, calibrations = fit_all(y, z, seed)
    save(folder / "pilot_bootstrap_indices.json", indices)
    diagnostics, missing = [], []
    for (world, mode), cal in calibrations.items():
        save(folder / f"{world}_{mode}.json", cal)
        new = transform(y[60:], z, world)
        value, support = transport_score(cal["plugin"], new, z)
        good = support.all(1)
        diagnostics.append(
            {
                "world": world,
                "mode": mode,
                "status": cal["plugin"]["status"],
                "validation_authors": int(good.sum()),
                "rmse": float(np.sqrt(np.mean((value[good] - y[60:][good]) ** 2)))
                if good.any()
                else None,
                "condition_residuals": {
                    str(q): float((value[good] - y[60:][good])[:, z == q].mean())
                    for q in [-1, 1]
                }
                if good.any()
                else {},
                "bootstrap_statuses": [c["status"] for c in cal["draws"]],
            }
        )
    for world in WORLDS:
        new = transform(y[:60], z, world)
        ix = np.tile(z, 60) == -1
        c = fit_transport(
            y[:60].ravel()[ix], new.ravel()[ix], np.tile(z, 60)[ix], "conditional"
        )
        if c["status"] != "MISSING_ANCHOR":
            raise ValueError("missing anchor was silently inferred")
        missing.append({"world": world, **c})
    save(folder / "pilot_validation.json", diagnostics)
    save(folder / "missing_anchors.json", missing)
    save(
        ready,
        {
            "seed": seed,
            "smoke": smoke,
            "source_file": str(old_path),
            "source_sha256": public.file_hash(old_path),
            "hashes": {
                p.name: public.file_hash(p)
                for p in sorted(folder.iterdir())
                if p.is_file() and not p.name.startswith(".")
            },
        },
    )


def inputs(folder, world, arm, y, z):
    """Build plugin/bootstrap observation bases, preserving failed calibrator support."""
    new = transform(y, z, world)
    if arm in ("uncalibrated", "known_inverse"):
        value = new if arm == "uncalibrated" else known_inverse(new, z, world)
        return (
            value[..., None],
            np.ones((1, 1)),
            np.ones(len(y), bool),
            slice(0, 1),
            slice(0, 1),
            0.0,
        )
    c = json.loads((folder / f"{world}_{arm}.json").read_text())
    models = [c["plugin"], *c["draws"]]
    basis, coef, support = law.inverse_basis(new, z, models)
    if not support.any():
        # Current prescribed failure is the cubic plugin itself. Do not discard a
        # supported plugin merely because a bootstrap failed in a future packet.
        pb, pc, ps = law.inverse_basis(new, z, [c["plugin"]])
        if ps.any():
            return pb, pc, ps, slice(0, 1), None, None
        return None, None, support, None, None, None
    error = 0.0
    for j, fit in enumerate(models):
        direct, ok = transport_score(fit, new, z)
        if not ok[support].all():
            raise ValueError("basis inferred extra support")
        error = max(error, float(abs(basis @ coef[j] - direct[support]).max()))
    if error > 1e-9:
        raise ValueError(f"inverse basis mismatch {error}")
    return basis, coef, support, slice(0, 1), slice(1, None), error


def work(arguments):
    """Score one seed with no truth-file access; checkpoint every complete arm."""
    output, seed, smoke = arguments
    folder = output / str(seed)
    started = time.monotonic()
    source = json.loads((folder / "source_bundle.json").read_text())
    path, ids, sy, z = source_records(seed)
    if public.file_hash(path) != source["source_hash"]["source"] or len(ids) != 300:
        raise ValueError("original source identity mismatch")
    models = [s["model"] for s in source["source_models"]]
    if smoke:
        models, sy = models[:3], sy[:5]
    kernels = [law.compile_source(m, z, 64) for m in models]
    ref_path = folder / "reference_moments.npz"
    if not ref_path.exists():
        moments = law.integrate(kernels, sy[..., None], np.ones((1, 1)))
        reference = law.collapse(moments, slice(None))
        np.savez(ref_path, **reference)
        scores = reference["mean"]
        save(
            folder / "reference.json",
            {
                "mu": scores.mean(0),
                "sigma": scores.std(0, ddof=1),
                "source_authors": len(sy),
                "source_hash": public.file_hash(path),
                "source_parameters_refitted": False,
                "formula": "conditional-Gaussian64eta-source-cut-v1",
                "legacy_reference_not_reused": True,
            },
        )
    print(f"dynamic transport seed={seed} source reference complete", flush=True)
    app = np.load(folder / "application_observations.npz")
    y = app["old"][:3] if smoke else app["old"]
    np.testing.assert_array_equal(app["conditions"], z)
    # Reuse common covariances, not latent labels. The larger node count is a
    # fixed numerical check, never selected by application prediction accuracy.
    fine = [law.compile_source(m, z, 128) for m in models]
    rd = folder / "reference_quadrature.json"
    if not rd.exists():
        r128 = law.collapse(
            law.integrate(fine, sy[[0, -1], :, None], np.ones((1, 1))), slice(None)
        )
        reference = np.load(ref_path)
        save(
            rd,
            {
                "score_max": float(
                    abs(r128["mean"] - reference["mean"][[0, -1]]).max()
                ),
                "variance_max": float(
                    abs(r128["covariance"] - reference["covariance"][[0, -1]]).max()
                ),
            },
        )
    for world in WORLDS:
        for arm in [
            "uncalibrated",
            "global",
            "conditional",
            "known_inverse",
            *(["cubic"] if world == "nonlinear" else []),
        ]:
            name = f"{world}_{arm}"
            summary_path = folder / f"{name}_summary.json"
            if summary_path.exists():
                continue
            before = time.monotonic()
            basis, coef, support, plugin, mixture, inverse_error = inputs(
                folder, world, arm, y, z
            )
            if support.any():
                all_moments = law.integrate(kernels, basis, coef)
                np.savez(folder / f"{name}_all_moments.npz", **all_moments)
                for label, selector in [("plugin", plugin), ("mixture", mixture)]:
                    if selector is not None:
                        np.savez(
                            folder / f"{name}_{label}.npz",
                            support=support,
                            **law.collapse(all_moments, selector),
                        )
                fixed = [0, len(basis) - 1]
                f128 = law.integrate(fine, basis[fixed], coef)
                check = {
                    "mean": float(
                        abs(f128["mean"] - all_moments["mean"][:, fixed]).max()
                    )
                }
                for part in ("state_future", "personal", "source"):
                    check[part] = float(
                        abs(f128[part] - all_moments[part][:, fixed]).max()
                    )
                check["conditional_indices"] = np.flatnonzero(support)[fixed].tolist()
                numerical = (
                    max(
                        check[k] for k in ("mean", "state_future", "personal", "source")
                    )
                    <= 0.02
                )
                save(folder / f"{name}_quadrature.json", check)
            else:
                numerical = None
            save(
                summary_path,
                {
                    "seed": seed,
                    "world": world,
                    "arm": arm,
                    "support": support,
                    "plugin_supported": bool(support.any() and plugin is not None),
                    "mixture_supported": bool(support.any() and mixture is not None),
                    "inverse_replay_error": inverse_error,
                    "quadrature_diagnostic_pass": numerical,
                    "seconds": time.monotonic() - before,
                },
            )
            print(
                f"dynamic transport seed={seed} {name} support={support.sum()}/{len(y)} seconds={time.monotonic() - before:.1f}",
                flush=True,
            )
    terminal = folder / "scoring_complete.json"
    if not terminal.exists():
        save(
            terminal,
            {
                "seed": seed,
                "status": "ALL_ARMS_SCORED_TRUTH_NOT_READ",
                "application_authors": len(y),
                "source_models": len(models),
                "seconds": time.monotonic() - started,
                "hashes": {
                    p.name: public.file_hash(p)
                    for p in sorted(folder.iterdir())
                    if p.is_file() and not p.name.startswith(".")
                },
            },
        )


def evaluate(output):
    """Open latent evaluation truth only after all observed-only scorers finish."""
    protocol = json.loads((output / "protocol_before_run.json").read_text())
    rows, summary = [], []
    for seed in protocol["seeds"]:
        folder = output / str(seed)
        check = json.loads((folder / "scoring_complete.json").read_text())
        for name, digest in check["hashes"].items():
            if public.file_hash(folder / name) != digest:
                raise ValueError("scored input/output changed before evaluation")
        truth = np.load(folder / "application_truth.npz")
        ref = json.loads((folder / "reference.json").read_text())
        n = check["application_authors"]
        for path in sorted(folder.glob("*_summary.json")):
            if path.name.startswith("."):
                continue
            s = json.loads(path.read_text())
            for estimator in ("plugin", "mixture"):
                p = folder / f"{s['world']}_{s['arm']}_{estimator}.npz"
                arr = np.load(p) if p.exists() else None
                supported = np.flatnonzero(arr["support"]) if arr is not None else []
                index = {int(person): j for j, person in enumerate(supported)}
                for t, target in enumerate(("T2", "T3")):
                    group = []
                    for i in range(n):
                        row = {
                            "seed": seed,
                            "world": s["world"],
                            "arm": s["arm"],
                            "estimator": estimator,
                            "target": target,
                            "author_index": i,
                            "truth": float(truth[target][i]),
                            "supported": i in index,
                            "score": None,
                            "variance": None,
                            "lower": None,
                            "upper": None,
                            "reference_score": None,
                            "state_future": None,
                            "personal": None,
                            "source": None,
                            "pilot": None,
                        }
                        if i in index:
                            j = index[i]
                            m, v = (
                                float(arr["mean"][j, t]),
                                float(arr["covariance"][j, t, t]),
                            )
                            if v <= 0:
                                raise ValueError("nonpositive prediction variance")
                            row.update(
                                score=m,
                                variance=v,
                                lower=m - 1.96 * np.sqrt(v),
                                upper=m + 1.96 * np.sqrt(v),
                                reference_score=(m - ref["mu"][t]) / ref["sigma"][t],
                            )
                            row.update(
                                {
                                    key: float(arr[key][j, t, t])
                                    for key in (
                                        "state_future",
                                        "personal",
                                        "source",
                                        "pilot",
                                    )
                                }
                            )
                        rows.append(row)
                        group.append(row)
                    g = pd.DataFrame(group)
                    good = g[g.supported]
                    metrics = {
                        key: group[0][key]
                        for key in ("seed", "world", "arm", "estimator", "target")
                    }
                    metrics.update(
                        n=n,
                        supported=len(good),
                        mse=None,
                        r=None,
                        coverage=None,
                        width=None,
                        pilot_variance=None,
                        wilson_low=None,
                        wilson_high=None,
                        gate=None,
                    )
                    if len(good) > 1:
                        coverage = np.mean(
                            (good.lower <= good.truth) & (good.truth <= good.upper)
                        )
                        count, v = len(good), 1.96**2
                        center = (coverage + v / (2 * count)) / (1 + v / count)
                        half = (
                            1.96
                            * np.sqrt(
                                coverage * (1 - coverage) / count + v / (4 * count**2)
                            )
                            / (1 + v / count)
                        )
                        metrics.update(
                            mse=float(np.mean((good.score - good.truth) ** 2)),
                            r=float(np.corrcoef(good.score, good.truth)[0, 1]),
                            coverage=float(coverage),
                            width=float((good.upper - good.lower).mean()),
                            pilot_variance=float(good.pilot.mean()),
                            wilson_low=float(center - half),
                            wilson_high=float(center + half),
                            gate=bool(center - half <= 0.95 <= center + half),
                        )
                    summary.append(metrics)
    pd.DataFrame(rows).to_csv(output / "predictions.csv", index=False)
    metrics = pd.DataFrame(summary)
    metrics.to_csv(output / "metrics_by_seed.csv", index=False)
    metrics.groupby(["world", "arm", "estimator", "target"], sort=True)[
        ["mse", "r", "coverage", "width", "pilot_variance", "supported"]
    ].mean().reset_index().to_csv(output / "metrics.csv", index=False)
    save(
        output / "summary.json",
        {
            "status": "NUMERIC_DYNAMIC_TRANSPORT_EXECUTED_AUDIT_REQUIRED",
            "source_models_per_seed": 3 if protocol["smoke"] else 200,
            "pilot_bootstraps": 200,
            "application_authors": sum(
                json.loads((output / str(s) / "scoring_complete.json").read_text())[
                    "application_authors"
                ]
                for s in protocol["seeds"]
            ),
            "prediction_rows": len(rows),
            "numeric_target_only": True,
            "scope": "new conditional-Gaussian eta integration;not old Laplace identity or text/human accuracy",
        },
    )
    save(
        output / "output_manifest.json",
        {
            str(p.relative_to(output)): public.file_hash(p)
            for p in sorted(output.rglob("*"))
            if p.is_file()
            and not p.name.startswith(".")
            and p.name != "output_manifest.json"
        },
    )


def main():
    """Prepare all pilots, score independently, then evaluate in a separate process."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--smoke", action="store_true")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--evaluate-only", action="store_true")
    parser.add_argument("--workers", type=int, default=3)
    args = parser.parse_args()
    if args.evaluate_only:
        evaluate(args.output)
        return
    protocol = {
        "seeds": [20260915] if args.smoke else [20260915, 20260916, 20260917],
        "smoke": args.smoke,
        "full_scope": "source200,pilot100/60-40/bootstrap200,application200,48prefix/future4,allfourmaps",
        "source_parameters_refitted": False,
        "hashes": {p: public.file_hash(ROOT / p) for p in FILES},
    }
    if args.resume:
        if (
            json.loads((args.output / "protocol_before_run.json").read_text())
            != protocol
        ):
            raise ValueError("resume protocol/code mismatch")
    else:
        args.output.mkdir(parents=True, exist_ok=False)
        save(args.output / "protocol_before_run.json", protocol)
        for name in FILES:
            target = args.output / "source_snapshot" / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ROOT / name, target)
    for seed in protocol["seeds"]:
        prepare(args.output, seed, args.smoke)
    jobs = [(args.output, seed, args.smoke) for seed in protocol["seeds"]]
    if args.workers == 1:
        for job in jobs:
            work(job)
    else:
        with ProcessPoolExecutor(max_workers=args.workers) as pool:
            list(pool.map(work, jobs))
    subprocess.run(
        [sys.executable, __file__, "--output", str(args.output), "--evaluate-only"],
        check=True,
    )


if __name__ == "__main__":
    main()
