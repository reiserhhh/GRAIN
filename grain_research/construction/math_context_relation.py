def code_hash():
    """Bind the scoring law, not any fit to model outputs."""
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def build_bundle(p, y, tolerance=1e-10, max_sweeps=10000):
    """Compile two fixed6+6 SOURCE families retaining all profile constraints."""
    p, y = np.asarray(p, float), np.asarray(y, float)
    if p.ndim != 4 or p.shape[1:] != (2, 2, 8):
        raise ValueError("Two views with two normalized eight-cell halves required")
    tables, fields, receipts = [], [], []
    for v in range(2):
        profiles, t, receipt = M.construct(p[:, v], y, tolerance, max_sweeps)
        tables.append(t)
        fields.append(M.fields(M.target_laws(profiles, t)))
        receipts.append(receipt)
    a = np.asarray(fields)
    return {
        "version": VERSION,
        "code_hash": code_hash(),
        "models": list(M.MODELS),
        "profiles": profiles.tolist(),
        "profile_tables": np.asarray(tables).tolist(),
        "pair_fields": np.where(np.isfinite(a), a, None).tolist(),
        "prior": y.mean(0).tolist(),
        "denominator": 36,
        "half_size": 6,
        "solver_receipts": receipts,
    }


def validate_bundle(b):
    """Check complete declared law shape and field derivation,including zeros."""
    keys = {
        "version",
        "code_hash",
        "models",
        "profiles",
        "profile_tables",
        "pair_fields",
        "prior",
        "denominator",
        "half_size",
        "solver_receipts",
    }
    if (
        set(b) != keys
        or b["version"] != VERSION
        or b["code_hash"] != code_hash()
        or b["models"] != list(M.MODELS)
        or b["denominator"] != 36
        or b["half_size"] != 6
    ):
        raise ValueError("Changed observation law or undeclared fitting field")
    profiles, t = np.asarray(b["profiles"]), np.asarray(b["profile_tables"], float)
    f, pi = np.asarray(b["pair_fields"], float), np.asarray(b["prior"], float)
    if (
        profiles.ndim != 2
        or profiles.shape[1] != 5
        or not np.isin(profiles, (0, 1)).all()
        or len(np.unique(profiles, axis=0)) != len(profiles)
        or t.shape != (2, 3, len(profiles), 8, 8)
        or np.any(t < 0)
        or not np.isfinite(t).all()
        or f.shape != (2, 3, 5, 8, 8)
        or pi.shape != (5,)
        or not np.isfinite(pi).all()
        or np.any((pi <= 0) | (pi >= 1))
    ):
        raise ValueError("Invalid SOURCE profiles,tables or target fields")
    for v in range(2):
        direct = M.fields(M.target_laws(profiles, t[v]))
        if not np.allclose(f[v], direct, rtol=0, atol=2e-15, equal_nan=True):
            raise ValueError("Pair field not generated by its SOURCE observation law")
    return b


def pair_sum(field, cells, slots, denominator=36):
    """Keep original-frame pair mass;an empty sum is not a neutral posterior."""
    f, c, s = np.asarray(field, float), np.asarray(cells), np.asarray(slots)
    if (
        f.shape[-2:] != (8, 8)
        or c.ndim != 1
        or s.shape != c.shape
        or not np.issubdtype(c.dtype, np.integer)
        or not np.issubdtype(s.dtype, np.integer)
        or np.any((c < 0) | (c > 7))
        or np.any((s < 0) | (s > 11))
        or len(set(s.tolist())) != len(s)
        or denominator != 36
    ):
        raise ValueError("Unique original slots and supported integer cells required")
    left, right = c[s < 6], c[s >= 6]
    n = len(left) * len(right)
    value = np.zeros(f.shape[:-2])
    known = np.ones(f.shape[:-2], bool)
    for a in left:
        for b in right:
            known &= np.isfinite(f[..., a, b])
            value += f[..., a, b]
    value = np.where(known, value / denominator, np.nan)
    average = value * denominator / n if n else np.full_like(value, np.nan)
    return value, average, known, n


def context_action(values):
    """Finite R+S versus R+C contact contrast with SAME S/C subset identities."""
    x = np.asarray(values, float)
    if x.shape[0] != 5:
        raise ValueError("All five historical natural conditions required")
    return x[2] - x[1] - x[3] + x[4]


def contact_action(field, cells, selected, control):
    """Direct cross-half R-to-S minus R-to-C account,not a fitted effect."""
    c, s, ctrl = np.asarray(cells), set(selected), set(control)
    if c.shape != (12,) or len(s) != 4 or len(ctrl) != 4 or s & ctrl:
        raise ValueError("Twelve events and disjoint four-event S/C required")
    if not (s | ctrl) <= set(range(12)):
        raise ValueError("Out-of-frame event identity")
    rest, f = set(range(12)) - s - ctrl, np.asarray(field, float)
    value = np.zeros(f.shape[:-2])
    for i in range(6):
        for j in range(6, 12):
            sign = int((i in rest and j in s) or (i in s and j in rest))
            sign -= int((i in rest and j in ctrl) or (i in ctrl and j in rest))
            if sign:
                value += sign * f[..., c[i], c[j]] / 36
    return value


def cold_record(bundle, record):
    """Score only event IDs,original slots and numerical cells;reject outcomes."""
    if set(record) != {"author_key", "view", "events"}:
        raise ValueError("Cold input excludes targets and native answers")
    v, events = record["view"], record["events"]
    if (
        type(v) is not int
        or v not in (0, 1)
        or not isinstance(record["author_key"], str)
    ):
        raise ValueError("Declared view and author identity required")
    if any(set(e) != {"event_id", "slot", "cell"} for e in events):
        raise ValueError("Only event ID,slot and cell are allowed")
    ids = [e["event_id"] for e in events]
    if any(not isinstance(i, str) for i in ids) or len(set(ids)) != len(ids):
        raise ValueError("Distinct identified evidence events required")
    slots, cells = [e["slot"] for e in events], [e["cell"] for e in events]
    if any(type(i) is not int for i in slots + cells):
        raise ValueError("Integer slots/cells required,not boolean or floats")
    mass, average, known, n = pair_sum(
        np.asarray(bundle["pair_fields"], float)[v],
        np.asarray(cells, int),
        np.asarray(slots, int),
    )
    clean = lambda x: np.where(np.isfinite(x), x, None).tolist()
    return {
        "author_key": record["author_key"],
        "view": v,
        "events": len(events),
        "pairs": n,
        "pair_mass_readout": clean(mass),
        "conditional_pair_average": clean(average),
        "supported": known.tolist(),
        "status": "PAIR_OBSERVED" if n else "NO_PAIR_OPPORTUNITY",
    }


def signed_agreement(x, y):
    """Descriptive signs/cosine without fitting scale,offset or predicting labels."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    good = np.isfinite(x) & np.isfinite(y)
    x, y = x[good], y[good]
    denom = np.linalg.norm(x) * np.linalg.norm(y)
    active = (np.abs(x) > 2e-12) & (np.abs(y) > 2e-12)
    return {
        "observations": len(x),
        "missing": int(good.size - good.sum()),
        "nonzero_pairs": int(active.sum()),
        "numerically_unresolved_pairs": int(len(x) - active.sum()),
        "fixed_numerical_resolution": 2e-12,
        "same_sign": int(np.count_nonzero((x * y > 0) & active)),
        "opposite_sign": int(np.count_nonzero((x * y < 0) & active)),
        "cosine": float(x @ y / denom) if denom else None,
        "mathematical_rms": float(np.sqrt(np.mean(x * x))) if len(x) else None,
        "native_rms": float(np.sqrt(np.mean(y * y))) if len(y) else None,
    }
